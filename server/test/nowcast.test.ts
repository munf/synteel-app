import assert from 'node:assert/strict';
import { test } from 'node:test';
import type { Log, LogData, Pond } from '../src/domain.ts';
import { knowledge } from '../src/knowledge.ts';
import { computeNowcast, simulate, thermalParams, type NowcastInput } from '../src/nowcast.ts';
import type { Threshold } from '../src/rules.ts';
import type { WeatherHour } from '../src/weather.ts';

const thresholds = knowledge.thresholds.parameters as Threshold[];
const HOUR = 3600_000;
const tz = 'Asia/Jakarta';
// 2026-10-28 10:00 WIB
const now = Date.parse('2026-10-28T03:00:00Z');

/** Clear tropical days: air 24 °C before dawn to 32 °C mid-afternoon, sun 06–18 WIB. */
function weather(opts: { rainAt?: number } = {}): WeatherHour[] {
  const hours: WeatherHour[] = [];
  for (let t = now - 8 * 24 * HOUR; t <= now + 2 * 24 * HOUR; t += HOUR) {
    const local = (new Date(t).getUTCHours() + 7) % 24;
    const airTemp = 28 - 4 * Math.cos(((local - 3) / 24) * 2 * Math.PI);
    const radiation = local >= 6 && local <= 18 ? 900 * Math.sin(((local - 6) / 12) * Math.PI) : 0;
    hours.push({ t, airTemp, radiation, cloud: 20, wind: 5, rain: opts.rainAt !== undefined && Math.abs(t - opts.rainAt) < 2 * HOUR ? 6 : 0 });
  }
  return hours;
}

const pond = (p: Partial<Pond> = {}): Pond => ({
  id: 1, name: 'Kolam C', kind: 'beton', volumeL: 3600, areaM2: 12,
  setting: 'outdoor', shaded: true, aeration: 'full', depthCm: 30, ...p,
});

let nextId = 1;
const log = (hoursAgo: number, data: LogData): Log => ({
  id: nextId++, pondId: 1, batchId: 1, loggedAt: new Date(now - hoursAgo * HOUR).toISOString(), source: 'manual', data,
});

const run = (over: Partial<NowcastInput> = {}) =>
  computeNowcast({ pond: pond(), phase: 'elver', density: 50, logs: [], weather: weather(), thresholds, now, timezone: tz, ...over });

test('the estimate starts exactly at the latest reading', () => {
  const nc = run({ logs: [log(0, { readings: { temperature: 28.4 } })] });
  assert.equal(nc.now.temp, 28.4);
  assert.equal(nc.basis.anchor?.value, 28.4);
});

test('an outdoor pond warms through a sunny afternoon, an indoor tank much less', () => {
  const logs = [log(0, { readings: { temperature: 28 } })];
  const at = (nc: ReturnType<typeof run>, h: number) => nc.hours.find((p) => p.t === now + h * HOUR)!.temp!;
  const outdoor = run({ logs, pond: pond({ shaded: false }) });
  const indoor = run({ logs, pond: pond({ setting: 'indoor' }) });
  assert.ok(at(outdoor, 5) - 28 > 1.5, `outdoor rose only to ${at(outdoor, 5)}`);
  assert.ok(Math.abs(at(indoor, 5) - 28) < 1, `indoor moved to ${at(indoor, 5)}`);
});

test('uncertainty grows with time since the last reading', () => {
  const nc = run({ logs: [log(0, { readings: { temperature: 28 } })] });
  const sigma = (h: number) => nc.hours.find((p) => p.t === now + h * HOUR)!.sigma!;
  assert.ok(sigma(2) < sigma(12) && sigma(12) < sigma(24));
});

test('calibration learns a pond that runs warmer than the model', () => {
  // Readings generated by the model itself with a +1.5 °C offset.
  const readings: Log[] = [];
  const w = new Map(weather().map((h) => [h.t, h]));
  let temp = 28;
  for (let h = 72; h >= 10; h -= 10) {
    temp = simulate(w, thermalParams(pond()), 1.5, now - h * HOUR, temp, now - (h - 10) * HOUR)!;
    readings.unshift(log(h - 10, { readings: { temperature: Number(temp.toFixed(2)) } }));
  }
  const nc = run({ logs: readings });
  assert.ok(nc.basis.calibrationPairs >= 2);
  assert.ok(Math.abs(nc.basis.offset - 1.5) < 0.3, `offset ${nc.basis.offset}`);
});

test('a calm, aerated, recently checked pond is low risk', () => {
  const nc = run({ logs: [log(1, { readings: { temperature: 28.5 }, behavior: ['normal'], aeration: 'on' })] });
  assert.equal(nc.now.level, 'ok');
});

test('an aerator reported off makes the risk critical, with the reason', () => {
  const nc = run({ logs: [log(1, { readings: { temperature: 28.5 }, aeration: 'off' })] });
  assert.equal(nc.now.level, 'critical');
  assert.equal(nc.now.factors[0].id, 'aeration_off');
});

test('surfacing eels and warm water add up', () => {
  const nc = run({ phase: 'glass_eel', logs: [log(1, { readings: { temperature: 30.6 }, behavior: ['surfacing'] })] });
  assert.deepEqual(nc.now.factors.map((f) => f.id).slice(0, 2).sort(), ['signs', 'temp']);
  assert.equal(nc.now.level, 'critical');
});

test('green water raises night risk outdoors only', () => {
  const logs = [log(1, { readings: { temperature: 28.5 }, water: { color: 'green' } })];
  const night = (nc: ReturnType<typeof run>) => nc.hours.find((p) => (new Date(p.t).getUTCHours() + 7) % 24 === 2 && p.t > now)!;
  assert.ok(night(run({ logs })).factors.some((f) => f.id === 'algae_night'));
  assert.ok(!night(run({ logs, pond: pond({ setting: 'indoor' }) })).factors.some((f) => f.id === 'algae_night'));
});

test('a pond nobody has looked at for 12 hours is flagged', () => {
  const nc = run({ logs: [log(13, { readings: { temperature: 28 } })] });
  assert.ok(nc.now.factors.some((f) => f.id === 'unwatched' && f.label === 'Belum dicek 13 jam'));
});

test('heavy rain is a factor for outdoor ponds', () => {
  const nc = run({ weather: weather({ rainAt: now }), logs: [log(1, { readings: { temperature: 28 } })] });
  assert.ok(nc.now.factors.some((f) => f.id === 'rain'));
});

test('suggested checks follow the daily routine in farm-local time', () => {
  const nc = run({ logs: [log(1, { readings: { temperature: 28 } })] });
  const local = nc.checks.map((c) => new Date(c.t + 7 * HOUR).toISOString().slice(11, 16));
  assert.deepEqual(local, ['12:00', '17:00', '21:00', '06:30']);
});

test('a night-time risk gets a check before it, marked as an alarm', () => {
  // Partial aeration plus green water and a crowded pond: risk rises at night.
  const nc = run({
    density: 120,
    pond: pond({ aeration: 'partial' }),
    logs: [log(1, { readings: { temperature: 28 }, water: { color: 'green' } })],
  });
  const alarm = nc.checks.find((c) => c.alarm);
  assert.ok(alarm, 'expected an alarm check');
  assert.match(alarm!.reason, /Risiko/);
});

test('without weather the estimate holds the last reading and widens fast', () => {
  const nc = run({ weather: [], logs: [log(2, { readings: { temperature: 28.2 } })] });
  assert.equal(nc.now.temp, 28.2);
  assert.equal(nc.basis.weather, false);
  assert.ok(nc.hours.at(-1)!.sigma! > 2);
});

test('no readings and no weather: no temperature, but risk still works', () => {
  const nc = run({ weather: [], logs: [log(1, { aeration: 'off' })] });
  assert.equal(nc.now.temp, null);
  assert.equal(nc.now.level, 'critical');
});
